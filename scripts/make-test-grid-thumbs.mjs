// Builds the 40 small tiles for the "more tests, more winners" animation (TestWinners.tsx):
// picks static ads round-robin across brands (variety), writes 240px WebP thumbs to
// public/test-grid/NN.webp and src/data/testGrid.ts. Re-run after adding static ads:
//   node scripts/make-test-grid-thumbs.mjs
import fs from 'node:fs'
import sharp from 'sharp'

const TILE_COUNT = 40
const src = fs.readFileSync('src/data/staticAds.ts', 'utf8')
const ads = [...src.matchAll(/brand: '([^']+)',\s*src: '([^']+)'/g)].map(([, brand, path]) => ({ brand, path }))
if (!ads.length) throw new Error('No ads parsed from staticAds.ts')

const byBrand = new Map()
for (const ad of ads) {
  if (!byBrand.has(ad.brand)) byBrand.set(ad.brand, [])
  byBrand.get(ad.brand).push(ad)
}
const queues = [...byBrand.values()]
const picks = []
for (let round = 0; picks.length < TILE_COUNT; round++) {
  let added = false
  for (const q of queues) {
    if (q[round] && picks.length < TILE_COUNT) {
      picks.push(q[round])
      added = true
    }
  }
  if (!added) break
}

fs.mkdirSync('public/test-grid', { recursive: true })
const out = []
for (const [i, ad] of picks.entries()) {
  const name = `${String(i + 1).padStart(2, '0')}.webp`
  await sharp(`public${ad.path}`).resize(240, 240, { fit: 'cover' }).webp({ quality: 70 }).toFile(`public/test-grid/${name}`)
  out.push(`  { src: '/test-grid/${name}', brand: ${JSON.stringify(ad.brand)} },`)
}
fs.writeFileSync(
  'src/data/testGrid.ts',
  `// Generated by scripts/make-test-grid-thumbs.mjs — 240px thumbs of real static ads for TestWinners.tsx\nexport const TEST_GRID_ADS: { src: string; brand: string }[] = [\n${out.join('\n')}\n]\n`,
)
console.log(`${picks.length} tiles from ${queues.length} brands`)
